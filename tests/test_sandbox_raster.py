def test_plain_text_document_yields_text_and_no_images():
    out = run_script(b"REFERRAL: 42 y/o, rectal bleeding", "referral.txt")
    assert out["images"] == []
    assert "42 y/o" in out["text"]


def test_corrupt_pdf_yields_empty_output_not_a_crash():
    """Empty text is what pipeline.py already treats as unparseable ->
    ESCALATE. The script must never raise, or exit_code would be non-zero
    and the failure mode would be a sandbox error instead of a triage one."""
    out = run_script(b"%PDF-1.4 this is not actually a pdf", "broken.pdf")
    assert out["images"] == []
    assert out["text"] == ""


def test_corrupt_image_yields_empty_output_not_a_crash():
    out = run_script(b"\x89PNG\r\n\x1a\n garbage after the header", "broken.png")
    assert out["images"] == []


def test_script_always_prints_exactly_one_json_object():
    for content, name in [
        (make_pdf(), "a.pdf"),
        (make_png(), "b.png"),
        (b"plain", "c.txt"),
        (b"", "d.pdf"),
    ]:
        out = run_script(content, name)
        assert set(out) == {"text", "images"}


def test_document_bytes_cannot_break_out_of_the_preamble():
    """The payload is embedded as a JSON-escaped literal; a filename that
    looks like code must stay data."""
    hostile = '"; import os; os.system("echo pwned"); FILENAME = "x.txt'
    out = run_script(b"harmless", hostile)
    assert out["images"] == []
